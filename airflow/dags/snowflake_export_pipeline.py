"""
Snowflake export orchestration DAG.

This DAG orchestrates the export of Gold datasets
to consolidated Parquet files for Snowflake ingestion.

Pipeline:
    Gold datasets -> Spark export -> Parquet validation

Airflow is responsible for orchestration only.
The actual data processing remains implemented in Spark.
"""


import docker

from datetime import datetime

from pathlib import Path
from airflow import DAG
from airflow.exceptions import AirflowException
from airflow.operators.bash import BashOperator
from airflow.operators.python import PythonOperator


# Configuration

# Existing Spark job container
SPARK_CONTAINER = "spark-job"

# Gold datasets produced by the existing pipeline
GOLD_DATASETS = [
    "hourly_metrics",
    "product_metrics",
    "user_metrics",
]

# Local export directory shared between Docker containers
from config.config import (
    GOLD_PATH,
    SNOWFLAKE_EXPORT_PATH
)

# Check Gold datasets availability
def check_gold_datasets():
    for dataset in GOLD_DATASETS:
        dataset_path = Path(GOLD_PATH) / dataset

        if not dataset_path.exists():
            raise AirflowException(
                f"Gold dataset not found: {dataset_path}"
            )

        if not list(dataset_path.rglob("*.parquet")):
            raise AirflowException(
                f"No parquet files found in {dataset_path}"
            )
        print(f"Gold dataset available: {dataset_path}")

        
# Execute Spark export job

def export_gold_to_snowflake():
    """
    Execute the Spark export job inside the existing spark-job
    container.

    The job reads Gold datasets and generates consolidated
    Parquet exports under /lake/snowflake_export.
    """

    client = docker.from_env()

    try:
        # Reuse the existing Spark job container.
        container = client.containers.get(SPARK_CONTAINER)
        container.reload()

        if container.status != "running":
            raise AirflowException(
                f"spark-job must be running. "
                f"Current status: {container.status}"
            )

        # Execute the Spark export script
        command = [
            "python3",
            "/opt/spark/jobs/export_gold_to_snowflake.py",
        ]

        print(f"Executing: {' '.join(command)}")

        result = container.exec_run(
            cmd=command,
            stdout=True,
            stderr=True,
            demux=True,
        )

        stdout, stderr = result.output or (None, None)

        if stdout:
            print(stdout.decode("utf-8", errors="replace"))

        if stderr:
            print(stderr.decode("utf-8", errors="replace"))

        if result.exit_code != 0:
            raise AirflowException(
                "Snowflake export job failed "
                f"(exit code: {result.exit_code})"
            )

        print("Gold datasets successfully exported.")

    finally:
        client.close()


# Validate generated Parquet exports

def validate_snowflake_exports():
    """
    Validate the Parquet exports generated by Spark.

    Each dataset must contain:
    - Exactly one Parquet file.
    - A Spark _SUCCESS marker.
    - A non-empty Parquet file.
    """

    # Normalize the export path to a pathlib.Path object.
    export_root = Path(SNOWFLAKE_EXPORT_PATH)

    print(f"Validating exports in: {export_root}")

    if not export_root.is_dir():
        raise AirflowException(
            f"Export directory does not exist: {export_root}"
        )

    for dataset in GOLD_DATASETS:

        dataset_path = export_root / dataset

        if not dataset_path.is_dir():
            raise AirflowException(
                f"Export dataset directory not found: {dataset_path}"
            )

        # Find generated Parquet files.
        parquet_files = list(
            dataset_path.glob("*.parquet")
        )

        if len(parquet_files) != 1:
            raise AirflowException(
                f"Expected exactly one Parquet file for "
                f"{dataset}, found {len(parquet_files)}"
            )

        parquet_file = parquet_files[0]

        # Check that the Parquet file is not empty.
        if parquet_file.stat().st_size == 0:
            raise AirflowException(
                f"Parquet file is empty: {parquet_file}"
            )

        # Check Spark write completion marker.
        success_marker = dataset_path / "_SUCCESS"

        if not success_marker.exists():
            raise AirflowException(
                f"Spark success marker not found: {success_marker}"
            )

        print(
            f"Validated {dataset}: "
            f"{parquet_file.name} "
            f"({parquet_file.stat().st_size} bytes)"
        )

    print("All Snowflake exports successfully validated.")


# DAG definition

with DAG(
    dag_id="snowflake_export_pipeline",

    # First logical execution date
    start_date=datetime(2026, 1, 1),

    # Manual execution during development
    #schedule=None,
    # Run the pipeline automatically at the beginning of every hour.
    schedule="0 * * * *",

    # Only one active execution at a time
    max_active_runs=1,

    # Do not create historical DAG runs
    catchup=False,

    description=(
        "Export Gold datasets to consolidated Parquet "
        "files for Snowflake ingestion."
    ),

    tags=[
        "ecommerce",
        "spark",
        "snowflake",
        "export",
    ],

) as dag:

    # Task 1: Check Gold datasets availability

    # check_gold = PythonOperator(
    #     task_id="check_gold_datasets",
    #     python_callable=check_gold_datasets,
    # )

    check_gold = BashOperator(
        task_id="check_gold_datasets",

        bash_command=f"""
            set -e

            for dataset in {" ".join(GOLD_DATASETS)}; do

                dataset_path="{GOLD_PATH}/${{dataset}}"

                if [ ! -d "$dataset_path" ]; then
                    echo "ERROR: Gold dataset not found: $dataset_path"
                    exit 1
                fi

                if ! find "$dataset_path" \
                    -type f -name '*.parquet' \
                    -print -quit | grep -q .; then

                    echo "ERROR: No Parquet files found in $dataset_path"
                    exit 1
                fi

                echo "Gold dataset available: $dataset_path"

            done
        """,
    )
    
    # Task 2: Execute Spark export

    run_spark_export = PythonOperator(
        task_id="run_spark_export",
        python_callable=export_gold_to_snowflake,
    )

    # Task 3: Validate generated exports

    validate_exports = PythonOperator(
        task_id="validate_snowflake_exports",
        python_callable=validate_snowflake_exports,
    )

    # Task dependencies
    # 1. Check Gold datasets availability
    # 2. Execute Spark export
    # 3. Validate generated exports
    check_gold >> run_spark_export >> validate_exports