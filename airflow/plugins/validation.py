
import json
import time

from airflow.exceptions import AirflowException

from pathlib import Path
from urllib.request import urlopen
from urllib.error import URLError, HTTPError

from config.config import (
    GOLD_PATH,
    GOLD_DATASETS,
    SNOWFLAKE_EXPORT_PATH,
    SPARK_MASTER_URL,
    SPARK_WORKER_CHECK_TIMEOUT,
    SPARK_WORKER_CHECK_INTERVAL,
    MIN_FREE_CORES,
    MIN_FREE_MEMORY_MB
)

# Check Gold datasets availability
def check_gold_datasets():
    for dataset in GOLD_DATASETS:
        dataset_path = Path(GOLD_PATH) / dataset

        if not dataset_path.exists():
            raise AirflowException(
                f"Gold dataset not found: {dataset_path}"
            )

        if not list(dataset_path.rglob("*.parquet")):
            raise AirflowException(
                f"No parquet files found in {dataset_path}"
            )
        print(f"Gold dataset available: {dataset_path}")


# Check Spark Worker availability

def check_spark_worker():
    """
    Check that at least one Spark Worker is registered,
    alive and has sufficient free resources.

    The function queries the Spark Master REST API.

    Airflow waits for a maximum of 60 seconds before
    raising an exception if no suitable Worker is available.
    """

    start_time = time.time()

    print("Checking Spark Worker availability...")
    print(f"Spark Master API: {SPARK_MASTER_URL}")

    while time.time() - start_time < SPARK_WORKER_CHECK_TIMEOUT:

        try:
            # Query the Spark Master REST API.
            with urlopen(
                SPARK_MASTER_URL,
                timeout=5
            ) as response:

                master_status = json.loads(
                    response.read().decode("utf-8")
                )

            workers = master_status.get("workers", [])

            # Keep only Workers registered as ALIVE.
            alive_workers = [
                worker
                for worker in workers
                if worker.get("state") == "ALIVE"
            ]

            print(
                f"Registered Workers: {len(workers)} | "
                f"Alive Workers: {len(alive_workers)}"
            )

            # Check available resources on each Worker.
            for worker in alive_workers:

                total_cores = worker.get("cores", 0)
                used_cores = worker.get("coresused", 0)

                total_memory = worker.get("memory", 0)
                used_memory = worker.get("memoryused", 0)

                free_cores = total_cores - used_cores
                free_memory = total_memory - used_memory

                print(
                    f"Worker {worker.get('id')}: "
                    f"{free_cores} free cores, "
                    f"{free_memory} MB free memory"
                )

                # Accept the Worker only if sufficient
                # resources are available.
                if (
                    free_cores >= MIN_FREE_CORES
                    and free_memory >= MIN_FREE_MEMORY_MB
                ):

                    print(
                        "Spark Worker is available "
                        "and has sufficient resources."
                    )

                    return

            print(
                "No Spark Worker currently has "
                "sufficient available resources."
            )

        except (URLError, HTTPError, TimeoutError, OSError) as error:

            print(
                f"Unable to reach Spark Master: {error}"
            )

        except (json.JSONDecodeError, KeyError, TypeError) as error:

            raise AirflowException(
                f"Invalid Spark Master response: {error}"
            )

        # Wait before checking again.
        time.sleep(SPARK_WORKER_CHECK_INTERVAL)

    raise AirflowException(
        "No available Spark Worker found after "
        f"{SPARK_WORKER_CHECK_TIMEOUT} seconds. "
        "Spark export will not be executed."
    )

# Validate generated Parquet exports

def validate_snowflake_exports():
    """
    Validate the Parquet exports generated by Spark.

    Each dataset must contain:
    - Exactly one Parquet file.
    - A Spark _SUCCESS marker.
    - A non-empty Parquet file.
    """

    # Normalize the export path to a pathlib.Path object.
    export_root = Path(SNOWFLAKE_EXPORT_PATH)

    print(f"Validating exports in: {export_root}")

    if not export_root.is_dir():
        raise AirflowException(
            f"Export directory does not exist: {export_root}"
        )

    for dataset in GOLD_DATASETS:

        dataset_path = export_root / dataset

        if not dataset_path.is_dir():
            raise AirflowException(
                f"Export dataset directory not found: {dataset_path}"
            )

        # Find generated Parquet files.
        parquet_files = list(
            dataset_path.glob("*.parquet")
        )

        if len(parquet_files) != 1:
            raise AirflowException(
                f"Expected exactly one Parquet file for "
                f"{dataset}, found {len(parquet_files)}"
            )

        parquet_file = parquet_files[0]

        # Check that the Parquet file is not empty.
        if parquet_file.stat().st_size == 0:
            raise AirflowException(
                f"Parquet file is empty: {parquet_file}"
            )

        # Check Spark write completion marker.
        success_marker = dataset_path / "_SUCCESS"

        if not success_marker.exists():
            raise AirflowException(
                f"Spark success marker not found: {success_marker}"
            )

        print(
            f"Validated {dataset}: "
            f"{parquet_file.name} "
            f"({parquet_file.stat().st_size} bytes)"
        )

    print("All Snowflake exports successfully validated.")
