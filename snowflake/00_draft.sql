-- First analyze: number of order, their amount and their average amount per status
SELECT
    STATUS,
    COUNT(*) AS ORDER_COUNT,
    SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE,
    AVG(TOTAL_AMOUNT) AS AVG_ORDER_AMOUNT
FROM ORDERS
GROUP BY STATUS
ORDER BY TOTAL_REVENUE DESC;