-- Create a sample table for e-commerce orders
CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID NUMBER(10, 0),
    CUSTOMER_ID NUMBER(10, 0),
    ORDER_DATE TIMESTAMP_NTZ,
    STATUS VARCHAR(30),
    TOTAL_AMOUNT NUMBER(12, 2)
);

