USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;
USE WAREHOUSE ECOMMERCE_WH;

-- Load hourly metrics data into his corresponding table
-- COPY INTO loads data into a table / FROM shows path containing our parquet file
-- FILE_FORMAT use our parquet file format defined 
-- MATCH_BY_COLUMN_NAME relates parquet fields to SQL colums with their name instead of their position 
COPY INTO RAW_HOURLY_METRICS
FROM @ECOMMERCE_RAW_STAGE/hourly_metrics/
FILE_FORMAT = (FORMAT_NAME = 'ECOMMERCE_PARQUET_FORMAT')
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- Load product metrics data into his corresponding table
COPY INTO RAW_PRODUCT_METRICS
FROM @ECOMMERCE_RAW_STAGE/product_metrics/
FILE_FORMAT = (FORMAT_NAME = 'ECOMMERCE_PARQUET_FORMAT')
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- Load product metrics data into his corresponding table
COPY INTO RAW_USER_METRICS
FROM @ECOMMERCE_RAW_STAGE/user_metrics/
FILE_FORMAT = (FORMAT_NAME = 'ECOMMERCE_PARQUET_FORMAT')
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;


-- check the loading result
SELECT COUNT(*) AS TOTAL_ROWS
FROM RAW_HOURLY_METRICS;

SELECT COUNT(*) AS TOTAL_ROWS
FROM RAW_PRODUCT_METRICS;

SELECT COUNT(*) AS TOTAL_ROWS
FROM RAW_USER_METRICS;

SELECT 'RAW_HOURLY_METRICS' AS TABLE_NAME,
       COUNT(*) AS TOTAL_ROWS
FROM RAW_HOURLY_METRICS

UNION ALL

SELECT 'RAW_PRODUCT_METRICS',
       COUNT(*)
FROM RAW_PRODUCT_METRICS

UNION ALL

SELECT 'RAW_USER_METRICS',
       COUNT(*)
FROM RAW_USER_METRICS;