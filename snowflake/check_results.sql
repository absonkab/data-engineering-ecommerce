USE DATABASE ECOMMERCE_DB;

DESC TABLE ECOMMERCE_DB.RAW.RAW_HOURLY_METRICS;

DESC TABLE ECOMMERCE_DB.RAW.RAW_PRODUCT_METRICS;

DESC TABLE ECOMMERCE_DB.RAW.RAW_USER_METRICS;

SHOW VIEWS IN SCHEMA DBT_DEV_STAGING;
SHOW VIEWS IN SCHEMA DBT_DEV_INTERMEDIATE;
SHOW VIEWS IN SCHEMA DBT_DEV_MARTS;

-- staging data count
SELECT COUNT(*) FROM DBT_DEV_STAGING.STG_HOURLY_METRICS;
SELECT COUNT(*) FROM DBT_DEV_STAGING.STG_PRODUCT_METRICS;
SELECT COUNT(*) FROM DBT_DEV_STAGING.STG_USER_METRICS;

-- intermediate data count
SELECT COUNT(*) FROM DBT_DEV_INTERMEDIATE.INT_HOURLY_METRICS;
SELECT COUNT(*) FROM DBT_DEV_INTERMEDIATE.INT_PRODUCT_METRICS;
SELECT COUNT(*) FROM DBT_DEV_INTERMEDIATE.INT_USER_METRICS;

-- mart data count
SELECT COUNT(*) FROM DBT_DEV_MARTS.MART_HOURLY;
SELECT COUNT(*) FROM DBT_DEV_MARTS.MART_PRODUCT;
SELECT COUNT(*) FROM DBT_DEV_MARTS.MART_USER;

SELECT 'RAW_HOURLY_METRICS' AS table_name, COUNT(*) AS row_count
FROM ECOMMERCE_DB.RAW.RAW_HOURLY_METRICS
UNION ALL
SELECT 'RAW_PRODUCT_METRICS', COUNT(*)
FROM ECOMMERCE_DB.RAW.RAW_PRODUCT_METRICS
UNION ALL
SELECT 'RAW_USER_METRICS', COUNT(*)
FROM ECOMMERCE_DB.RAW.RAW_USER_METRICS;


SHOW SCHEMAS IN ECOMMERCE_DB;

